// The landing hosts the shared demo world. The daemon chunk loads lazily (loadWorld is a dynamic import in
// demo/api.ts), window.__naDemo is set BEFORE any iframe gets its src, so the desk and the phone frame join the
// same simulated computer. Everything here degrades: no world means the frames make their own.
import { loadWorld, sceneRoute, type DemoFrame, type DemoScene, type DemoView, type DemoWorld } from "../../demo/api";

let pending: Promise<DemoWorld | null> | undefined;

/** The shared world (created once, on demand). Resolves null when the daemon chunk fails to load. */
export function hostWorld(): Promise<DemoWorld | null> {
  if (typeof window === "undefined") return Promise.resolve(null);
  if (window.__naDemo) return Promise.resolve(window.__naDemo);
  pending ??= loadWorld({ scene: "grid" }).then(
    (w) => (window.__naDemo ??= w),
    () => null,
  );
  return pending;
}

/** Run `fn` when the browser is idle (after first paint), at the latest after `timeout` ms. */
export function whenIdle(fn: () => void, timeout = 1800): () => void {
  const w = window as Window & { requestIdleCallback?: (cb: () => void, o?: { timeout: number }) => number; cancelIdleCallback?: (n: number) => void };
  if (w.requestIdleCallback) {
    const id = w.requestIdleCallback(fn, { timeout });
    return () => w.cancelIdleCallback?.(id);
  }
  const id = window.setTimeout(fn, 400);
  return () => clearTimeout(id);
}

/** A visitor on a slow or metered connection: do not pull the app bundle unasked. */
export function saveData(): boolean {
  const c = (navigator as Navigator & { connection?: { saveData?: boolean; effectiveType?: string } }).connection;
  return !!c && (c.saveData === true || c.effectiveType === "slow-2g" || c.effectiveType === "2g");
}

/** The control surface of a frame, once the frame's script has published it (it loads after the `load` event). */
export function waitForFrame(iframe: HTMLIFrameElement, timeout = 20000): Promise<DemoFrame | null> {
  return new Promise((resolve) => {
    const t0 = performance.now();
    const tick = () => {
      let f: DemoFrame | undefined;
      try {
        f = iframe.contentWindow?.__naDemoFrame;
      } catch {
        f = undefined;
      }
      if (f) return resolve(f);
      if (!iframe.isConnected || performance.now() - t0 > timeout) return resolve(null);
      setTimeout(tick, 80);
    };
    tick();
  });
}

/** Where a scene starts a frame (the world sends frames there itself; late joiners are told once). */
export const startRoute = (scene: DemoScene, view: DemoView) => sceneRoute(scene, view);

/** `/demo/` URL of a frame. `traffic=0`: the site draws its own window controls. */
export function frameSrc(view: DemoView, scene: DemoScene): string {
  const p = new URLSearchParams({ view, embed: "1", scene });
  if (view === "desk") p.set("traffic", "0");
  return `/demo/?${p}`;
}

/** The full-screen demo page for a scene (opened by "Try it live" and "Open full demo"). */
export const demoHref = (scene: DemoScene, view: DemoView = "desk") => `/demo/?view=${view}&scene=${scene}`;

/** Posters live in public/demo/{desk,phone}-<name>.webp (generated by scripts/dev/site-posters.mjs). */
export const posterSrc = (view: DemoView, name: string) => `/demo/${view}-${name}.webp`;
