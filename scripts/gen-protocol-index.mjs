// Writes packages/protocol/src/gen/index.ts re-exporting every ts-rs generated type.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../packages/protocol/src/gen/", import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith(".ts") && f !== "index.ts").sort();
const lines = files.map((f) => `export type * from "./${f.replace(/\.ts$/, "")}";`);
if (existsSync(join(dir, "serde_json"))) lines.push(`export type * from "./serde_json/JsonValue";`);
writeFileSync(join(dir, "index.ts"), `// Generated by scripts/gen-protocol-index.mjs. Do not edit.\n${lines.join("\n")}\n`);
console.log(`gen/index.ts: ${lines.length} exports`);
